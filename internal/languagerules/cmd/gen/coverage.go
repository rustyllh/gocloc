package main

import (
	"bytes"
	"fmt"
	"strings"
)

func coverageReport(
	upstream map[string]upstreamRule,
	mappings map[string]languageMapping,
	compiled map[string]compiledRule,
) []byte {
	var report bytes.Buffer
	active := 0
	for _, mapping := range mappings {
		if mapping.KeepLegacy == "" {
			active++
		}
	}
	report.WriteString("<!-- Generated by go generate ./...; DO NOT EDIT. -->\n\n# 语言规则覆盖报告\n\n")
	fmt.Fprintf(
		&report,
		"全量生成 %d 个 tokei 条目；已有 %d 个 gocloc 名称中，"+
			"%d 个启用新扫描器，%d 个保留历史行为。\n\n",
		len(upstream),
		len(mappings),
		active,
		len(mappings)-active,
	)
	report.WriteString("不导入扩展名、文件名、shebang 或 MIME；未新增可识别的文件类型。\n")
	report.WriteString("`blank` 是上游元数据，不表示非空行算空行。" +
		"`literate`、`kind` 和嵌入入口仅在下表记录，未启用文档或嵌入语言分类。\n\n")
	report.WriteString("## gocloc 名称映射\n\n| gocloc 名称 | tokei 条目 | 状态 |\n| --- | --- | --- |\n")
	for _, name := range sortedKeys(mappings) {
		mapping := mappings[name]
		status := "启用"
		if mapping.KeepLegacy != "" {
			status = "保留历史行为：" + mapping.KeepLegacy
		}
		fmt.Fprintf(
			&report,
			"| %s | %s | %s |\n",
			name,
			mapping.Source,
			status,
		)
	}
	report.WriteString("\n## 全量规则目录\n\n")
	report.WriteString("普通、原样、文档列为上游引号对数；本地补充见备注。" +
		"规则生成不等于对应语言已由 CLI 识别。\n\n")
	report.WriteString("| tokei 条目 | 普通 | 原样 | 文档 | 嵌套 | 元数据／本地补充 |\n" +
		"| --- | --- | --- | --- | --- | --- |\n")
	for _, name := range sortedKeys(upstream) {
		input := upstream[name]
		notes := metadataNotes(name, input)
		if rule := compiled[name]; rule.note != "tokei "+name {
			notes = append(notes, strings.TrimPrefix(rule.note, "tokei "+name+"; "))
		}
		nested := input.Nested || len(input.NestedComments) > 0
		fmt.Fprintf(
			&report,
			"| %s | %d | %d | %d | %t | %s |\n",
			name,
			len(input.Quotes),
			len(input.VerbatimQuotes),
			len(input.DocQuotes),
			nested,
			strings.ReplaceAll(strings.Join(notes, "; "), "|", "\\|"),
		)
	}
	return report.Bytes()
}

func metadataNotes(name string, input upstreamRule) []string {
	notes := []string{}
	if input.Blank {
		notes = append(notes, "blank (metadata)")
	}
	if input.Literate {
		notes = append(notes, "literate (deferred)")
	}
	if input.Kind != "" {
		notes = append(notes, "kind="+input.Kind+" (deferred)")
	}
	if len(input.Important) > 0 {
		notes = append(notes, "important_syntax="+strings.Join(input.Important, ", "))
	}
	if deferredSource(name) {
		notes = append(notes, "activation deferred")
	}
	return notes
}
